#!/usr/bin/env node
/**
 * Compiles the per-locale i18n source files (src/core/i18n/locales/*.ts, the
 * files developers edit) into the compact modules that actually ship
 * (src/core/i18n/generated/*.ts).
 *
 *  - generated/en.ts       KEYS (every English key text, once) + English values.
 *                          An empty string means "the value is the key itself".
 *  - generated/<locale>.ts Values only, aligned by index with KEYS. An empty
 *                          string means "not translated here, use English".
 *
 * Shipping index-aligned value arrays keeps the English key text out of every
 * locale chunk, so a page downloads English plus at most one locale chunk.
 *
 * Usage: node scripts/generate-i18n-chunks.mjs [--check]
 *   --check  exit 1 if the committed generated files are stale (no writes).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const ts = require('typescript')

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const localesDir = path.join(root, 'src/core/i18n/locales')
const generatedDir = path.join(root, 'src/core/i18n/generated')

export const LOCALE_FILES = {
  'zh-CN': { file: 'zh-CN.ts', exportName: 'zhCN' },
  'zh-TW': { file: 'zh-TW.ts', exportName: 'zhTW' },
  de: { file: 'de.ts', exportName: 'de' },
  ja: { file: 'ja.ts', exportName: 'ja' },
  ko: { file: 'ko.ts', exportName: 'ko' }
}

function loadSource(file, exportName) {
  const source = fs.readFileSync(path.join(localesDir, file), 'utf8')
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 }
  })
  const module = { exports: {} }
  // Locale sources only contain `import type`, which transpiles away.
  new Function('exports', 'module', 'require', outputText)(module.exports, module, () => {
    throw new Error(`${file} must not have runtime imports`)
  })
  const dictionary = module.exports[exportName]
  if (!dictionary || typeof dictionary !== 'object') {
    throw new Error(`${file} does not export ${exportName}`)
  }
  return dictionary
}

const literal = values => `[\n${values.map(value => `  ${JSON.stringify(value)}`).join(',\n')}\n]`

const banner = name =>
  `// GENERATED by scripts/generate-i18n-chunks.mjs from src/core/i18n/locales/${name}. Do not edit.\n// Run \`npm run i18n:generate\` after changing a locale source file.\n`

/** Returns { relativeFileName: contents } for every generated module. */
export function buildChunks() {
  const en = loadSource('en.ts', 'en')
  const keys = Object.keys(en)
  const out = {}
  for (const key of keys) {
    if (typeof en[key] !== 'string' || en[key] === '') {
      throw new Error(`English value for "${key}" must be a non-empty string`)
    }
  }
  const enValues = keys.map(key => (en[key] === key ? '' : en[key]))
  out['en.ts'] =
    `${banner('en.ts')}\n` +
    `export const KEYS: readonly string[] = ${literal(keys)}\n\n` +
    `/** English copy by key index; '' means the copy equals the key. */\n` +
    `export const VALUES: readonly string[] = ${literal(enValues)}\n`

  const keySet = new Set(keys)
  for (const [locale, { file, exportName }] of Object.entries(LOCALE_FILES)) {
    const dictionary = loadSource(file, exportName)
    for (const [key, value] of Object.entries(dictionary)) {
      if (!keySet.has(key)) throw new Error(`${file}: unknown key "${key}"`)
      if (typeof value !== 'string' || value === '') {
        throw new Error(`${file}: value for "${key}" must be a non-empty string`)
      }
    }
    const values = keys.map(key => dictionary[key] ?? '')
    out[`${locale}.ts`] =
      `${banner(file)}\n` +
      `/** Translations by English-key index; '' means fall back to English. */\n` +
      `const values: readonly string[] = ${literal(values)}\n\n` +
      `export default values\n`
  }
  return out
}

function main() {
  const check = process.argv.includes('--check')
  const chunks = buildChunks()
  let stale = false
  fs.mkdirSync(generatedDir, { recursive: true })
  for (const [name, contents] of Object.entries(chunks)) {
    const target = path.join(generatedDir, name)
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null
    if (current === contents) continue
    if (check) {
      console.error(`stale: src/core/i18n/generated/${name}`)
      stale = true
    } else {
      fs.writeFileSync(target, contents)
      console.log(`wrote src/core/i18n/generated/${name}`)
    }
  }
  if (check && stale) {
    console.error('i18n generated files are out of date. Run: npm run i18n:generate')
    process.exit(1)
  }
  if (check) console.log('i18n generated files are up to date')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
